#!/usr/bin/env node

/**
 * build-skill-cli.js — 构建 CLI 并把产物同步到 skill/cli。
 *
 * 背景：分发只走 skill 市场（Claude 插件市场 / Codex 插件市场 / skills.sh）。
 * 市场安装是 git clone，不会运行构建，因此 CLI 产物必须随 skill 提交进仓库：
 * skill/cli/ 就是「安装副本里可直接 node 运行的 CLI」，运行时不依赖 npm/PATH。
 *
 * 用法:
 *   node scripts/build-skill-cli.js          # 构建 + 同步
 *   node scripts/build-skill-cli.js --check  # CI 用：构建后校验产物已提交（有漂移则退出 1）
 */

import { execSync } from 'node:child_process';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.resolve(__dirname, '..');
const DIST = path.join(ROOT, 'packages', 'boss-cli', 'dist');
const DEST = path.join(ROOT, 'skill', 'cli');
const CHECK = process.argv.includes('--check');

const BUNDLE_PACKAGE_JSON = {
  name: 'boss-cli-skill-bundle',
  private: true,
  type: 'module',
  description:
    'Bundled Boss CLI for skill-marketplace installs. Generated by scripts/build-skill-cli.js — do not edit by hand.',
};

function build() {
  console.log('🔨 构建 CLI (tsc)...');
  execSync('npm run build', { cwd: ROOT, stdio: 'inherit' });
}

function sync() {
  if (!fs.existsSync(path.join(DIST, 'bin', 'boss.js'))) {
    throw new Error(`未找到构建产物: ${path.join(DIST, 'bin', 'boss.js')}`);
  }
  fs.rmSync(DEST, { recursive: true, force: true });
  fs.cpSync(DIST, DEST, { recursive: true });
  fs.writeFileSync(
    path.join(DEST, 'package.json'),
    `${JSON.stringify(BUNDLE_PACKAGE_JSON, null, 2)}\n`,
    'utf8',
  );
  console.log(`✅ 已同步 ${path.relative(ROOT, DIST)} → ${path.relative(ROOT, DEST)}`);
}

function checkClean() {
  const status = execSync(`git status --porcelain -- ${path.relative(ROOT, DEST)}`, {
    cwd: ROOT,
    encoding: 'utf8',
  }).trim();
  if (status) {
    console.error('❌ skill/cli 与源码不一致（构建产物漂移）。请运行 npm run build:skill 并提交:');
    console.error(status);
    process.exit(1);
  }
  console.log('✅ skill/cli 与源码一致');
}

build();
sync();

if (CHECK) {
  checkClean();
}
